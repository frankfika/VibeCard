import hre from 'hardhat';
import { writeFileSync, mkdirSync, existsSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

/**
 * 部署 VibeCard 完整生态系统
 * 1. VibePoints - 积分系统
 * 2. VibeIdentity - DID + SBT
 * 3. VibeSocial - 社交互动
 * 4. DappCardRegistry - 内容注册表（旧版）
 */
async function main() {
  const connection = await hre.network.getOrCreate();
  const ethers = connection.ethers;

  const [deployer] = await ethers.getSigners();
  console.log('\n🚀 Deploying VibeCard Ecosystem');
  console.log('═══════════════════════════════════════════════════════════');
  console.log('Deployer:', deployer.address);

  const balance = await ethers.provider.getBalance(deployer.address);
  console.log('Balance:', ethers.formatEther(balance), 'ETH');

  if (balance === 0n) {
    console.warn('⚠️  WARNING: Account has zero balance. Deployment may fail.');
  }

  const network = await ethers.provider.getNetwork();
  const chainId = Number(network.chainId);
  console.log('Network:', network.name);
  console.log('Chain ID:', chainId);
  console.log('═══════════════════════════════════════════════════════════\n');

  const deploymentInfo = {
    deployer: deployer.address,
    timestamp: new Date().toISOString(),
    network: network.name,
    chainId,
    contracts: {}
  };

  // 1. 部署 VibePoints
  console.log('📊 Deploying VibePoints...');
  const VibePoints = await ethers.getContractFactory('VibePoints');
  const vibePoints = await VibePoints.deploy();
  await vibePoints.waitForDeployment();
  const pointsAddress = await vibePoints.getAddress();
  console.log('✅ VibePoints deployed:', pointsAddress);
  deploymentInfo.contracts.VibePoints = pointsAddress;

  // 2. 部署 VibeIdentity
  console.log('\n🆔 Deploying VibeIdentity...');
  const VibeIdentity = await ethers.getContractFactory('VibeIdentity');
  const vibeIdentity = await VibeIdentity.deploy();
  await vibeIdentity.waitForDeployment();
  const identityAddress = await vibeIdentity.getAddress();
  console.log('✅ VibeIdentity deployed:', identityAddress);
  deploymentInfo.contracts.VibeIdentity = identityAddress;

  // 3. 部署 VibeSocial
  console.log('\n👥 Deploying VibeSocial...');
  const VibeSocial = await ethers.getContractFactory('VibeSocial');
  const vibeSocial = await VibeSocial.deploy(pointsAddress, identityAddress);
  await vibeSocial.waitForDeployment();
  const socialAddress = await vibeSocial.getAddress();
  console.log('✅ VibeSocial deployed:', socialAddress);
  deploymentInfo.contracts.VibeSocial = socialAddress;

  // 4. 部署 DappCardRegistry (旧版兼容)
  console.log('\n📝 Deploying DappCardRegistry (legacy)...');
  const DappCardRegistry = await ethers.getContractFactory('DappCardRegistry');
  const registry = await DappCardRegistry.deploy();
  await registry.waitForDeployment();
  const registryAddress = await registry.getAddress();
  console.log('✅ DappCardRegistry deployed:', registryAddress);
  deploymentInfo.contracts.DappCardRegistry = registryAddress;

  // 5. 设置权限：VibeSocial 作为 VibePoints 的 operator
  console.log('\n🔐 Setting up permissions...');
  const tx = await vibePoints.addOperator(socialAddress);
  await tx.wait();
  console.log('✅ VibeSocial added as VibePoints operator');

  // 6. 保存部署信息
  const deploymentsDir = resolve(__dirname, '../deployments');
  if (!existsSync(deploymentsDir)) {
    mkdirSync(deploymentsDir, { recursive: true });
  }

  // 保存带时间戳的历史记录
  const historyFilename = `ecosystem-${network.name}-${Date.now()}.json`;
  writeFileSync(
    resolve(deploymentsDir, historyFilename),
    JSON.stringify(deploymentInfo, null, 2)
  );

  // 保存当前网络的标准文件
  const canonicalFilename = `ecosystem-${network.name}.json`;
  writeFileSync(
    resolve(deploymentsDir, canonicalFilename),
    JSON.stringify(deploymentInfo, null, 2)
  );

  console.log('\n💾 Deployment info saved:');
  console.log(`   - deployments/${historyFilename}`);
  console.log(`   - deployments/${canonicalFilename}`);

  // 7. 生成前端配置
  console.log('\n📱 Generating frontend config...');

  const frontendConfig = `// Auto-generated by deploy-ecosystem.js
// Last updated: ${new Date().toISOString()}

export const VIBE_ECOSYSTEM_ADDRESSES: Record<number, {
  VibePoints: string;
  VibeIdentity: string;
  VibeSocial: string;
  DappCardRegistry: string;
}> = {
  [${chainId}]: {
    VibePoints: '${pointsAddress}',
    VibeIdentity: '${identityAddress}',
    VibeSocial: '${socialAddress}',
    DappCardRegistry: '${registryAddress}',
  },
};

// 积分配置
export const POINTS_REWARDS = {
  CREATE_PROFILE: '50',
  DAILY_SIGNIN: '5',
  INTERACTION: '10',
  ACTIVITY_HOST: '30',
  ACTIVITY_JOIN: '15',
  ACTIVITY_REWARD: '20',
  UGC_CARD: '20',
  CARD_USED: '1',
  INVITE: '100',
  FOLLOW: '2',
};

export const POINTS_COSTS = {
  PREMIUM_TEMPLATE: '100',
  PIN_ACTIVITY: '50',
  RARE_CARD_PACK: '30',
  PRIVATE_ACTIVITY: '20',
};
`;

  const frontendConfigPath = resolve(__dirname, '../../web/src/lib/web3/ecosystem.ts');
  writeFileSync(frontendConfigPath, frontendConfig);
  console.log('✅ Frontend config generated:', 'src/lib/web3/ecosystem.ts');

  // 8. 显示摘要
  console.log('\n═══════════════════════════════════════════════════════════');
  console.log('🎉 Deployment Complete!');
  console.log('═══════════════════════════════════════════════════════════');
  console.log('Contract Addresses:');
  console.log('  VibePoints:        ', pointsAddress);
  console.log('  VibeIdentity:      ', identityAddress);
  console.log('  VibeSocial:        ', socialAddress);
  console.log('  DappCardRegistry:  ', registryAddress);
  console.log('═══════════════════════════════════════════════════════════');

  console.log('\n📋 Next Steps:');
  console.log('1. Update .env with contract addresses (if needed)');
  console.log('2. Run: npm run build (in web package)');
  console.log('3. Test the points system:');
  console.log('   - Connect wallet');
  console.log('   - Create profile → earn 50 points');
  console.log('   - Daily signin → earn 5 points');
  console.log('   - Interact → earn 10 points');
  console.log('\n💡 Verify on explorer:', `https://etherscan.io/address/${socialAddress}`);
}

main().catch((error) => {
  console.error('❌ Deployment failed:', error);
  process.exitCode = 1;
});
